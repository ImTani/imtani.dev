import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { createLogger, defineConfig } from 'vite';

import { articleInputs, quietArticleMedia, writing } from './tools/writing/vite-plugin.ts';

const here = dirname(fileURLToPath(import.meta.url));

export default defineConfig(({ command }) => ({
  // Only the build has warnings to quiet; see quietArticleMedia.
  customLogger: quietArticleMedia(createLogger()),
  plugins: [writing()],
  build: {
    outDir: 'dist',
    target: 'es2022',
    rollupOptions: {
      input: {
        // index.html is the public holding page and is plain HTML with no
        // script at all; harness.html carries the engine and is noindex.
        // Keeping them separate means the placeholder ships nothing it does
        // not need, and the harness stays reachable without being what the
        // domain serves.
        index: resolve(here, 'index.html'),
        harness: resolve(here, 'harness.html'),
        // One page per published article, generated by tools/writing/build.ts,
        // which runs before Vite in the build script — Rollup needs each file
        // on disk to take it as an entry. Each emits to dist/writing/<slug>.html,
        // which the assets runtime serves at /writing/<slug> without the
        // extension. Read from the article list, never from drafts, and only
        // for a build: the dev server serves whatever is in writing/.
        ...(command === 'build' ? articleInputs() : {}),
      },
    },
    // The engine is small and entirely interdependent; splitting it costs a
    // round trip and saves nothing.
    modulePreload: { polyfill: false },
    reportCompressedSize: true,
  },
  server: { port: 5173, strictPort: false },
}));
